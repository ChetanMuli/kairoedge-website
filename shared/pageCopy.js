export function mergeCopy(base, saved) {
  if (!saved || typeof saved !== "object") return base;
  const next = {};
  const allSections = new Set([...Object.keys(base), ...Object.keys(saved)]);
  for (const section of allSections) {
    const baseSection = base[section] || {};
    const savedSection = (saved && typeof saved[section] === "object") ? saved[section] : {};
    next[section] = { ...baseSection, ...savedSection };
  }
  return next;
}
